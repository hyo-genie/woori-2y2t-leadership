/* 픽셀 그리드 → SVG rect (가로 런렝스) */
function pixRects(rows, pal){
  var out = '';
  for (var y = 0; y < rows.length; y++){
    var row = rows[y], x = 0;
    while (x < row.length){
      var ch = row[x];
      if (ch === '.'){ x++; continue; }
      var x2 = x; while (x2 < row.length && row[x2] === ch) x2++;
      var col = (pal && pal[ch]) || PAL[ch] || '#f0f';
      out += '<rect x="'+x+'" y="'+y+'" width="'+(x2-x)+'" height="1" fill="'+col+'"/>';
      x = x2;
    }
  }
  return out;
}
function itemDef(type){
  var d = ITEMS[type]; if (!d) return null;
  var rows = d.rows || (d.ref && ITEMS[d.ref].rows);
  return { type:type, name:d.name, cat:d.cat, rows:rows, pal:d.pal||null, cols:rows[0].length, lines:rows.length };
}
var PX = 3.2;
function buildSymbols(){
  var s = '';
  Object.keys(ITEMS).forEach(function(t){
    var d = itemDef(t);
    s += '<symbol id="it-'+t+'" viewBox="0 0 '+d.cols+' '+d.lines+'" shape-rendering="crispEdges">'+pixRects(d.rows, d.pal)+'</symbol>';
  });
  return s;
}

